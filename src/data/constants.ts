export function calculateDistribution(amount: number, percentages: Record<AccountKey, number>): Record<AccountKey, number> {
  const totalPct = Object.values(percentages).reduce((sum, p) => sum + p, 0);
  if (totalPct <= 0 || amount <= 0) {
    return { C: 0, I: 0, M: 0, P: 0, R: 0, E: 0, S: 0 };
  }

  const result: Record<AccountKey, number> = { C: 0, I: 0, M: 0, P: 0, R: 0, E: 0, S: 0 };
  let allocated = 0;
  const keys = Object.keys(percentages) as AccountKey[];

  keys.forEach((key, index) => {
    if (index === keys.length - 1) {
      // Last account gets remaining to prevent rounding drifts
      result[key] = Math.max(0, Math.round((amount - allocated) * 100) / 100);
    } else {
      const share = Math.round((amount * (percentages[key] / totalPct)) * 100) / 100;
      result[key] = share;
      allocated += share;
    }
  });

  return result;
}

export function formatCurrency(amount: number, currency: string = '$'): string {
  const isNegative = amount < 0;
  const absVal = Math.abs(amount);
  const formatted = absVal.toLocaleString('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return `${isNegative ? '-' : ''}${currency}${formatted}`;
}

export function formatCompactCurrency(amount: number, currency: string = '$'): string {
  const absVal = Math.abs(amount);
  const isNegative = amount < 0;
  let str = '';
  if (absVal >= 1_000_000) {
    str = (absVal / 1_000_000).toFixed(1) + 'M';
  } else if (absVal >= 1_000) {
    str = (absVal / 1_000).toFixed(1) + 'k';
  } else {
    str = absVal.toFixed(0);
  }
  return `${isNegative ? '-' : ''}${currency}${str}`;
}

